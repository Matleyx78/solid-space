"""Compile validated corpus JSON into C++ values, without a C++ JSON dependency."""
import argparse
from fractions import Fraction
import math
from pathlib import Path
import re
import sys

from valida_corpus import (COMPONENTS, FRACTION_RE, PENDING_DIR, load_json,
                           load_pending_dir, validate_corpus)

HEX_RE = re.compile(r"[+-]?0[xX](?:[0-9a-fA-F]+(?:\.[0-9a-fA-F]*)?|\.[0-9a-fA-F]+)[pP][+-]?[0-9]+")

# The table is emitted one function per case. Building every case in a single
# expression needs a stack frame that grows with the number of cases (about 4 KB
# each): with 299 cases it passed the 1 MiB default stack of Windows and the test
# executable crashed at start-up. Each function keeps the temporaries of its own
# case, and cases() only loops over an array of function pointers.
PREAMBLE = '''// SPDX-License-Identifier: GPL-3.0-or-later
// Copyright (C) 2026 The solid-space authors
// Generated by genera_casi.py. Do not edit.
#include "operations.hpp"

#include <cstddef>
#include <span>
#include <vector>

namespace solid_space::corpus {
namespace {
'''
TABLE_BEGIN = '''}  // namespace

std::span<const Case> cases() {
    static const std::vector<Case> table = [] {
        using Maker = Case (*)();
        // The last entry is a sentinel, so that the array is never empty.
        static constexpr Maker makers[] = {
'''
TABLE_END = '''            nullptr}};
        constexpr std::size_t count = {count};
        std::vector<Case> rows;
        rows.reserve(count);
        for (const Maker make : std::span<const Maker>(makers, count)) {{
            rows.push_back(make());
        }}
        return rows;
    }}();
    return table;
}}
}}  // namespace solid_space::corpus
'''


def cpp_string(value):
    # Encode UTF-8 bytes with fixed-width octal escapes, also safe before digits.
    return '"' + ''.join(chr(b) if 32 <= b < 127 and b not in (34, 92)
                         else f"\\{b:03o}" for b in value.encode("utf-8")) + '"'


def cpp_double(value):
    number = float(value)
    if not math.isfinite(number):
        raise ValueError("number cannot be represented as a finite double")
    return number.hex()


def value_cpp(value, expected=False):
    if isinstance(value, bool):
        return f"Value::boolean({'true' if value else 'false'})"
    if isinstance(value, (int, float)):
        return f"Value::number({cpp_double(value)})"
    if isinstance(value, str):
        if expected:
            if FRACTION_RE.fullmatch(value):
                fraction = Fraction(value)
                try:
                    number = float(fraction)
                    exact = math.isfinite(number) and Fraction(number) == fraction
                except OverflowError:
                    exact = False
                argument = cpp_double(number) if exact else "std::nullopt"
                return f"Value::exact({cpp_string(value)}, {argument})"
            return f"Value::name({cpp_string(value)})"
        if HEX_RE.fullmatch(value):
            return f"Value::number({cpp_double(float.fromhex(value))})"
        return f"Value::text({cpp_string(value)})"
    if isinstance(value, list):
        return "Value::list({" + ", ".join(value_cpp(v, expected) for v in value) + "})"
    if expected and "valore" in value:
        return f"Value::approximate({cpp_double(value['valore'])}, {cpp_double(value['tolleranza'])})"
    return "Value::group({" + ", ".join(
        "{" + cpp_string(k) + ", " + value_cpp(v, expected) + "}"
        for k, v in value.items()) + "})"


def generate(root, output, components):
    root, output = Path(root), Path(output)
    problems = validate_corpus(root)
    if problems:
        raise ValueError("\n".join(map(str, problems)))
    paths = sorted((root / "casi").glob("*/*.json"))
    known = {f"{p.parent.name}/{p.stem}" for p in paths}
    pending, problems = load_pending_dir(root / PENDING_DIR, known)
    if problems:
        raise ValueError("\n".join(map(str, problems)))
    cases = [load_json(p, str(p))[0] for p in paths if p.parent.name in components]
    cases.sort(key=lambda case: (case["componente"], case["id"]))
    functions, required = [], []
    for index, case in enumerate(cases):
        key = case['componente'] + '/' + case['id']
        issue = pending.get(key, 0)
        if not issue:
            required.append(key)
        fields = ", ".join((cpp_string(case['id']), cpp_string(case['componente']), str(issue),
                            value_cpp(case['ingresso']), value_cpp(case['atteso'], True)))
        functions.append(f"Case makeCase{index}() {{\n    return {{{fields}}};\n}}\n")
    makers = "".join(f"            &makeCase{index},\n" for index in range(len(functions)))
    code = PREAMBLE + "\n".join(functions) + TABLE_BEGIN + makers + TABLE_END.format(
        count=len(functions))
    output.mkdir(parents=True, exist_ok=True)
    with (output / "casi.cpp").open("w", encoding="utf-8", newline="\n") as stream:
        stream.write(code)
    with (output / "obbligatori.txt").open("w", encoding="utf-8", newline="\n") as stream:
        stream.write("".join(k + "\n" for k in required))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("corpus", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--componenti", nargs="+", choices=COMPONENTS, required=True)
    args = parser.parse_args(argv)
    try:
        generate(args.corpus, args.output, args.componenti)
    except (OSError, ValueError, OverflowError) as error:
        print(error, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
